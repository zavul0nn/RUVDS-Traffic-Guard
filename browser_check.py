"""Run against a fresh local preview.py process. Needs optional Playwright."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

p=Path(__file__).parent/'artifacts'
p.mkdir(exist_ok=True)
url='http://127.0.0.1:8789/preview-hidden-path-0123456789'
errors=[]
with sync_playwright() as pw:
    browser=pw.chromium.launch()
    context=browser.new_context(viewport={'width':1440,'height':1060},ignore_https_errors=True)
    page=context.new_page()
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(url,wait_until='domcontentloaded')
    page.evaluate('document.fonts.ready')
    expect(page.locator('#login-form')).to_be_visible()
    page.screenshot(path=str(p/'login-desktop.png'),full_page=True)
    page.locator('#password').fill('preview-password-123')
    page.locator('#login-form button').click()
    expect(page.locator('#node-state')).to_have_text('Работает')
    expect(page.locator('#all-days tr')).to_have_count(5)
    page.screenshot(path=str(p/'panel-desktop-v3.png'),full_page=True)
    samples=page.evaluate("async () => (await (await fetch(document.documentElement.dataset.base+'api/history')).json()).samples")
    peak=max(samples,key=lambda s:s['rx'])
    expected=page.evaluate('(s) => ({rx:mbps(s.rx),tx:mbps(s.tx),time:dateTime(s.at)+" МСК"})',peak)
    page.locator('.chart-panel').scroll_into_view_if_needed()
    page.wait_for_timeout(350)
    bounds=page.locator('#traffic-chart').bounding_box()
    fraction=page.evaluate('(at)=>(at-(Date.now()/1000-86400))/86400',peak['at'])
    page.mouse.move(bounds['x']+bounds['width']*(48+fraction*(786-48))/800,bounds['y']+bounds['height']*.45)
    expect(page.locator('#chart-point-rx')).to_have_text(expected['rx'])
    expect(page.locator('#chart-point-tx')).to_have_text(expected['tx'])
    expect(page.locator('#chart-point-time')).to_have_text(expected['time'])
    expect(page.locator('#chart-tooltip')).to_be_visible()
    page.screenshot(path=str(p/'chart-hover-desktop.png'),clip=page.locator('.chart-panel').bounding_box())
    page.mouse.move(20,20)
    expect(page.locator('#chart-tooltip')).to_be_hidden()
    page.locator('#traffic-chart').focus()
    page.keyboard.press('Home')
    expect(page.locator('#chart-tooltip')).to_be_visible()
    page.keyboard.press('ArrowRight')
    page.keyboard.press('End')
    page.keyboard.press('Escape')
    expect(page.locator('#chart-tooltip')).to_be_hidden()
    page.locator('[data-hours="1"]').click()
    expect(page.locator('[data-hours="1"]')).to_have_attribute('aria-pressed','true')
    expect(page.locator('.chart-panel .panel-heading p')).to_contain_text('последний час')
    page.evaluate('drawChart([])')
    expect(page.locator('#chart-empty')).to_be_visible()
    expect(page.locator('#chart-tooltip')).to_be_hidden()
    page.locator('[data-hours="24"]').click()
    page.evaluate('drawChart([{at:Date.now()/1000-4000,rx:1e6,tx:2e6},{at:Date.now()/1000-400,rx:3e6,tx:4e6}])')
    bounds=page.locator('#traffic-chart').bounding_box()
    page.mouse.move(bounds['x']+bounds['width']*(48+(1-2200/86400)*(786-48))/800,bounds['y']+bounds['height']*.45)
    expect(page.locator('#chart-point-rx')).to_have_text('Нет измерений')
    page.mouse.move(20,20)
    page.locator('[data-hours="6"]').click()
    page.locator('[data-hours="24"]').click()
    page.locator('#pause').click()
    expect(page.locator('#node-state')).to_have_text('Остановлена',timeout=10000)
    page.locator('#resume').click()
    expect(page.locator('#node-state')).to_have_text('Работает',timeout=10000)
    page.locator('[data-tab="history"]').click()
    expect(page.locator('#history')).to_be_visible()
    with page.expect_download() as download:
        page.locator('#export').click()
    download.value.save_as(str(p/'preview-history.csv'))
    assert 'day,used,rx,tx,complete,updated' in (p/'preview-history.csv').read_text()
    page.locator('[data-tab="events"]').click()
    expect(page.locator('#event-list .event')).not_to_have_count(0)
    page.locator('[data-tab="settings"]').click()
    expect(page.locator('#limit-gb')).to_have_value('145')
    page.locator('#limit-gb').fill('0')
    page.locator('#policy-stop').focus()
    expect(page.locator('#settings-error')).not_to_be_empty()
    page.locator('#limit-gb').fill('1')
    page.locator('#save-settings').click()
    expect(page.locator('#settings-feedback')).to_have_text('Сохранено. Настройки уже действуют.',timeout=10000)
    expect(page.locator('#node-state')).to_have_text('Остановлена')
    page.locator('#policy-monitor').check()
    page.locator('#save-settings').click()
    expect(page.locator('#save-settings')).to_be_disabled(timeout=10000)
    expect(page.locator('#node-state')).to_have_text('Работает')
    expect(page.locator('#state-badge')).to_have_text('Порог превышен')
    page.reload()
    page.locator('[data-tab="settings"]').click()
    expect(page.locator('#limit-gb')).to_have_value('1')
    expect(page.locator('#policy-monitor')).to_be_checked()
    page.locator('#limit-gb').fill('145,5')
    page.wait_for_timeout(5500)
    expect(page.locator('#limit-gb')).to_have_value('145,5')
    page.locator('#policy-stop').check()
    page.locator('#save-settings').click()
    expect(page.locator('#save-settings')).to_be_disabled(timeout=10000)
    expect(page.locator('#limit-gb')).to_have_value('145.5')
    expect(page.locator('#toast')).to_be_hidden(timeout=8000)
    page.screenshot(path=str(p/'settings-desktop-v2.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Settings mobile overflow'
    page.screenshot(path=str(p/'settings-mobile-v2.png'),full_page=True)
    page.set_viewport_size({'width':1440,'height':1060})
    page.locator('#limit-gb').fill('145')
    page.locator('#save-settings').click()
    expect(page.locator('#save-settings')).to_be_disabled(timeout=10000)
    page.locator('[data-tab="overview"]').click()
    page.set_viewport_size({'width':390,'height':844})
    expect(page.locator('#traffic-chart')).to_have_attribute('viewBox','0 0 800 260',timeout=8000)
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Mobile overflow'
    expect(page.locator('#toast')).to_be_hidden(timeout=8000)
    page.screenshot(path=str(p/'panel-mobile-v3.png'),full_page=True)
    touch=browser.new_context(viewport={'width':390,'height':844},has_touch=True,is_mobile=True)
    touch.add_cookies(context.cookies())
    mobile=touch.new_page()
    mobile.on('pageerror',lambda error:errors.append(str(error)))
    mobile.goto(url,wait_until='domcontentloaded')
    expect(mobile.locator('#peak-rx')).not_to_have_text('—')
    mobile.locator('#traffic-chart').scroll_into_view_if_needed()
    box=mobile.locator('#traffic-chart').bounding_box()
    mobile.touchscreen.tap(box['x']+box['width']*.55,box['y']+box['height']*.6)
    expect(mobile.locator('#chart-tooltip')).to_be_visible()
    assert mobile.evaluate('document.documentElement.scrollWidth <= innerWidth'), 'Touch tooltip overflow'
    touch.close()
    page.locator('#rearm').click()
    expect(page.locator('#rearm-dialog')).to_be_visible()
    page.locator('#rearm-dialog button[value="cancel"]').click()
    expect(page.locator('#rearm-dialog')).not_to_be_visible()
    page.locator('#rearm').click()
    page.locator('#confirm-rearm').click()
    expect(page.locator('#state-badge')).to_have_text('Ожидание 03:00',timeout=10000)
    expect(page.locator('#node-state')).to_have_text('Остановлена')
    expect(page.locator('#resume')).to_be_disabled()
    page.locator('[data-tab="settings"]').click()
    expect(page.locator('#setting-target')).to_have_text('remnanode')
    page.set_viewport_size({'width':1440,'height':1060})
    page.locator('#logout').click()
    expect(page.locator('#login-form')).to_be_visible()
    assert not errors, errors
    browser.close()
print('Browser QA passed: measured peak tooltip, keyboard, touch, time ranges, gaps, empty chart, login, stop/start, CSV, live settings, mobile, recovery, logout; no JS errors.')
